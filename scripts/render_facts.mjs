// Render results/facts.json into docs/RESUME_FACTS.md and the README block
// between <!-- FACTS-BEGIN --> and <!-- FACTS-END -->. Numbers are copied,
// never typed. Usage: node scripts/render_facts.mjs [--check]
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = process.cwd();
const f = JSON.parse(readFileSync(join(ROOT, "results", "facts.json"), "utf-8"));
const kib = (b) => (b / 1024).toFixed(1);
const lp = f.largest_sample_parse;
const bp = f.browser_parse;

const rows = [
  ["Largest sample", `\`${lp.sample}\`: ${lp.trace_events.toLocaleString("en-US")} trace events (${lp.gpu_events.toLocaleString("en-US")} GPU events), ${kib(lp.json_bytes)} KiB of JSON (${kib(lp.file_bytes)} KiB gzipped)`, "results/facts.json → largest_sample_parse"],
  ["Parse + analyze in the browser Web Worker", bp.worker_total_ms_median !== undefined ? `${bp.worker_total_ms_median} ms median of ${bp.repeats} page loads (${bp.browser})` : `NOT RUN (${bp.status})`, "results/browser_parse.json (via facts.json → browser_parse)"],
  ["Parse + analyze in Node", `${lp.node_total_ms_median} ms median of ${lp.repeats} (JSON.parse alone ${lp.node_parse_ms_median} ms)`, "results/facts.json → largest_sample_parse"],
  ["Unit tests (Vitest)", `${f.unit_tests.passed} passed of ${f.unit_tests.total} in ${f.unit_tests.files} files`, "results/facts.json → unit_tests"],
  ["End-to-end tests (Playwright)", `${f.e2e_tests.total} tests in ${f.e2e_tests.files} file (pass/fail: CI run, see LOG.md)`, "results/facts.json → e2e_tests"],
  ["Production JS bundle", `${kib(f.bundle.js_bytes)} KiB (${kib(f.bundle.js_gzip_bytes)} KiB gzipped), incl. the worker chunk`, "results/facts.json → bundle"],
  ["Lighthouse / load metrics", `${f.lighthouse.status}: ${f.lighthouse.reason}`, "results/facts.json → lighthouse"],
];

const env = `${f.environment.cpu}, ${f.environment.os}, Node ${f.environment.node}; facts generated at commit \`${f.git_commit.slice(0, 7)}\` on ${f.date_utc}`;
const table = ["| Fact | Value | Source |", "|---|---|---|", ...rows.map((r) => `| ${r.join(" | ")} |`)].join("\n");

const resume = `# Resume facts (generated — do not edit)

Generated by \`scripts/render_facts.mjs\` from \`results/facts.json\`
(itself generated by \`scripts/facts.ts\` and \`scripts/screenshots.mjs\`).
Only verified numbers, each with the file it came from. These are facts,
not resume bullets.

Machine: ${env}.

${table}

Sample provenance: every file in \`data/\` has a \`.meta.json\` beside it
(GPU, driver, torch version, command, or the kern commit it was copied from).
`;

const block = `<!-- FACTS-BEGIN -->\n${table}\n\n<sub>Machine: ${env}. Generated by \`scripts/render_facts.mjs\`.</sub>\n<!-- FACTS-END -->`;

const check = process.argv.includes("--check");
const readmePath = join(ROOT, "README.md");
const readme = readFileSync(readmePath, "utf-8");
const newReadme = readme.replace(/<!-- FACTS-BEGIN -->[\s\S]*<!-- FACTS-END -->/, block);
const resumePath = join(ROOT, "docs", "RESUME_FACTS.md");
if (check) {
  const old = (() => { try { return readFileSync(resumePath, "utf-8"); } catch { return ""; } })();
  if (newReadme !== readme || old !== resume) {
    console.log("facts rendering is stale: run node scripts/render_facts.mjs");
    process.exit(1);
  }
  console.log("facts rendering is up to date");
} else {
  writeFileSync(readmePath, newReadme);
  writeFileSync(resumePath, resume);
  console.log("wrote README facts block and docs/RESUME_FACTS.md");
}
